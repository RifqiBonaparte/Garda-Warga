for each row execute procedure public.set_updated_at();

-- =========================
-- HELPER: CEK PETUGAS
-- =========================
create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'petugas'
  );
$$;

