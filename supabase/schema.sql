create extension if not exists pgcrypto;

-- =========================
-- PROFILES / AKUN WARGA
-- =========================
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nama text not null,
  email text unique not null,
  hp text default '-',
  rt text default '-',
  rw text default '-',
  role text not null default 'warga' check (role in ('warga','petugas')),
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Membuat profile otomatis ketika user mendaftar lewat Supabase Auth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, nama, email, hp, rt, rw, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nama', split_part(new.email, '@', 1)),
    lower(new.email),
    coalesce(new.raw_user_meta_data->>'hp', '-'),
    coalesce(new.raw_user_meta_data->>'rt', '-'),
    coalesce(new.raw_user_meta_data->>'rw', '-'),
    'warga'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- =========================
-- NOTIFIKASI
-- =========================
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade,
  text text not null,
  type text not null default 'umum',
  read boolean not null default false,
  created_at timestamptz not null default now()
);

-- user_id NULL = notifikasi untuk semua warga.
-- user_id terisi = notifikasi khusus satu warga.

-- =========================
-- JADWAL KEGIATAN
-- =========================
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  event_date date not null,
  start_time time,
  end_time time,
  lokasi text not null default '-',
  deskripsi text default '',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =========================
-- PENGADUAN
-- =========================
create table if not exists public.complaints (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  nama text not null,
  email text not null,
  kategori text not null,
  lokasi text not null,
  deskripsi text not null,
  foto_url text,
  status text not null default 'Dikirim'
    check (status in ('Dikirim','Diterima','Diproses','Selesai')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =========================
-- FORUM
-- =========================
create table if not exists public.forum_topics (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  judul text not null,
  isi text not null,
  is_pinned boolean not null default false,
  is_deleted boolean not null default false,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.forum_comments (
  id bigint generated by default as identity primary key,
  topic_id bigint not null references public.forum_topics(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  isi text not null,
  is_deleted boolean not null default false,
  deleted_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.forum_likes (
  topic_id bigint not null references public.forum_topics(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (topic_id, user_id)
);

-- =========================
-- UPDATED_AT
-- =========================
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at
before update on public.profiles
for each row execute procedure public.set_updated_at();

